# ------------------------------------------------------------------
# Real header staging (same symlink-into-a-framework-shaped-dir pattern
# build_corefoundation.sh/build_bootp_dhcp_engine.sh already established):
# every file in SystemConfiguration.fproj/ itself #includes its OWN
