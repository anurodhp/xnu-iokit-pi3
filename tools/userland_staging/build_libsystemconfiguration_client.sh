# Real, same-precedent-as-build_corefoundation_dylib.sh/build_libinfo.sh
# newer-ld requirement: Xcode-12's own default `ld` doesn't support
# `-Wl,-fixup_chains`/real `-Wl,-U` deferrals without a `dyld_stub_binder`
