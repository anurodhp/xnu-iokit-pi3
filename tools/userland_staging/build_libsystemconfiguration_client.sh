# Both real .defs files are regenerated here via mig (same "always
# regenerate, never commit generated MIG output" precedent as
# build_launchd_mig.sh/build_libmach_ipc.sh/build_libnotify.sh), CLIENT
# (User) side only -- config_server.c/SCHelper_server.c are real
# configd.tproj-side code, explicitly out of scope this session (DAR-170
# Tier 1 step 3, not this one).
#
# Real product-shape check (per this project's CLAUDE.md "prefer real
# dylibs over new static archives" rule + this ticket's own instruction to
# verify against real Apple structure, not guess): configd.xcodeproj's own
# project.pbxproj defines a real "SystemConfiguration.framework" /
# "SystemConfiguration.framework-Embedded" PBXNativeTarget (productType
# wrapper.framework) -- SystemConfiguration IS one of Apple's own real,
# separately-installed framework products (like CoreFoundation), not
# something meant to be statically embedded into each consumer. Matching
# this project's own already-established CF precedent (real framework,
# flattened to a plain .dylib at /usr/lib/ instead of a
# Versions/A/Frameworks bundle, since this project has no framework-bundle
# loader), this script produces a real
# libc_build/system/libSystemConfiguration.dylib, install_name
# /usr/lib/libSystemConfiguration.dylib -- NOT a new static archive.
