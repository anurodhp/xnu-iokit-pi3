enum {
	OS_STATE_DATA_SERIALIZED_NSCF_OBJECT = 2,
	OS_STATE_DATA_CUSTOM = 4,
};

struct os_state_data_s {
	uint32_t	osd_type;
	uint32_t	osd_data_size;
	char		osd_title[64];
	struct {
		char	osdd_library[32];
		char	osdd_type[32];
	} osd_decoder;
	uint8_t		osd_data[];
};
typedef struct os_state_data_s *os_state_data_t;

#define OS_STATE_DATA_SIZE_NEEDED(len) \
	(offsetof(struct os_state_data_s, osd_data) + (len))

typedef os_state_data_t (^os_state_block_t)(os_state_hints_t hints);

#ifdef __cplusplus
extern "C" {
#endif
os_state_handle_t os_state_add_handler(dispatch_queue_t q, os_state_block_t block);
#ifdef __cplusplus
}
#endif
#endif /* _OS_STATE_PRIVATE_H_COMPAT_ */
EOF

