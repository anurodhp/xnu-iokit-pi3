# Real architecture, confirmed by reading source (not assumed):
# `libSystemConfiguration/libSystemConfiguration_client.c` (the file this
# ticket's own state note names) is actually a SMALL, generic XPC
# connect-and-send-with-reply helper used by the separate DNS-configuration
# and NWI (network information) XPC clients (dnsinfo/nwi) -- it is NOT the
# SCDynamicStore/SCPreferences engine itself. The real SCDynamicStore/
# SCPreferences client API lives in SystemConfiguration.fproj/ as ~35
# files under two real naming families:
#   - SCD*.c (23 files): SCDynamicStore itself -- SCDynamicStoreCreate
#     (SCDOpen.c), Get/Set/Add/Remove/List/Keys, the 8 SCDNotifier*.c
#     notification files, SCDPrivate.c, SCDCache.c, SCDSnapshot.c,
#     SCDConsoleUser.c, SCDHostName.c, SCDPlugin.c (real SCDPluginExecCommand
#     child-process helper, part of the public/private SCDPlugin.h surface
#     these files themselves #include).
#   - SCP*.c (12 files): SCPreferences itself -- SCPOpen/Add/Get/Set/Remove/
#     List/Lock/Unlock/Apply/Commit/Path.c.
#   - helper/SCHelper_client.c: the real privileged-helper-tool IPC client
#     (_SCHelperOpen/_SCHelperExec/_SCHelperClose) SCPOpen.c/SCPLock.c/
#     SCPUnlock.c/SCPCommit.c/SCPApply.c call for privileged preference
#     writes -- its own small real MIG subsystem (helper.defs).
#   - SCSchemaDefinitions.c: real, already-generated (checked into the
#     pinned tag, NOT regenerated by genSCPreferences.c at our build time --
#     that generator needs a macosx.internal SDK this project doesn't have,
#     and the real output is already committed source in the pinned repo).
#   - libSystemConfiguration/libSystemConfiguration_client.c: included too,
#     both because the ticket names it explicitly and because it's real,
#     small, and self-contained.
# NOT in scope this pass (genuinely separate, much larger real subsystems):
# SCNetworkConfiguration*.c/SCNetworkInterface.c/SCNetworkConnection*.c/
# SCNetworkReachability.c/SCNetworkService.c/SCNetworkSet.c/Bond/Bridge/VLAN/
# VPN*.c/CaptiveNetwork.c/SCProxies.c/SCLocation.c/SCNetwork.c/
# scprefs_observer.c/SCPreferencesKeychainPrivate.c -- none of these are
# SCDynamicStore/SCPreferences core, matching this ticket's own framing
# ("the real SCDynamicStore/SCPreferences client API").
#
# Real transport, confirmed by reading SCDOpen.c directly (not guessed):
# SCDynamicStore uses raw MIG-generated Mach IPC (config.defs ->
# bootstrap_look_up() for "com.apple.SystemConfiguration.configd", then
# hand-written mach_msg-based routines configopen/configget/configset/...),
# NOT XPC. SCHelper (the privileged-helper client) also uses its own MIG
# subsystem (helper.defs) over a Mach port obtained via a forked/execed
# helper tool, also not XPC. Only libSystemConfiguration_client.c itself
# (the DNS/NWI helper, not core SCDynamicStore) uses xpc_connection_*.
# Both real .defs files are regenerated here via mig (same "always
# regenerate, never commit generated MIG output" precedent as
# build_launchd_mig.sh/build_libmach_ipc.sh/build_libnotify.sh), CLIENT
# (User) side only -- config_server.c/SCHelper_server.c are real
# configd.tproj-side code, explicitly out of scope this session (DAR-170
# Tier 1 step 3, not this one).
#
# Real product-shape check (per this project's CLAUDE.md "prefer real
# dylibs over new static archives" rule + this ticket's own instruction to
# verify against real Apple structure, not guess): configd.xcodeproj's own
# project.pbxproj defines a real "SystemConfiguration.framework" /
# "SystemConfiguration.framework-Embedded" PBXNativeTarget (productType
# wrapper.framework) -- SystemConfiguration IS one of Apple's own real,
# separately-installed framework products (like CoreFoundation), not
# something meant to be statically embedded into each consumer. Matching
# this project's own already-established CF precedent (real framework,
# flattened to a plain .dylib at /usr/lib/ instead of a
# Versions/A/Frameworks bundle, since this project has no framework-bundle
# loader), this script produces a real
# libc_build/system/libSystemConfiguration.dylib, install_name
# /usr/lib/libSystemConfiguration.dylib -- NOT a new static archive.
