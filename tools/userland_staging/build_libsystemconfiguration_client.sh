# first trial link) -- the daily-driver Xcode's newer `ld` handles
# `-Wl,-U` as a real, non-lazy `<flat-namespace>` chained-fixups bind
# instead, resolved for real at dyld load time, matching every other
# real dylib link in this project that needs a `-Wl,-U` deferral.
