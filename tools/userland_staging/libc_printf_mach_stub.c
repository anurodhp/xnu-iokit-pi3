/* Real Mach IPC (mach_msg_trap-based MIG calls like vm_region_64, plus the
 * task_self_trap() that seeds mach_task_self()) is not ported on this
 * target -- confirmed by reading third_party/xnu-7195/libsyscall/mach/:
 * unlike the plain BSD syscall layer (real Apple Perl generator, already
 * used by build_libsyscall_smoketest.sh), most Mach calls here are MIG
 * RPCs (mach_vm.defs -> mig-compiled stubs marshalling a mach_msg_trap()
 * call), not single raw traps -- bringing that up for real (port rights,
 * IPC space, the `mig` compiler itself) is a distinct, much larger future
 * project, same class of gap as the "no USB host controller driver"
 * structural gap in architecture.md, not something to fake here.
 *
 * The ONLY real Libc caller of vm_region_64()/mach_task_self() reached by
 * this project's curated build is stdio/FreeBSD/vfprintf.c's
 * __printf_is_memory_read_only() -- used exactly once, lazily, only when
 * a live %n conversion is encountered (see that function's real callers
 * in vfprintf.c: "if (!static_format_checked) ... os_crash(...)"). Its
 * real job is a security check: is the format string itself sitting in
 * read-only (i.e. genuinely static/literal, not attacker-writable heap or
 * stack) memory, so %n can't be turned into an arbitrary-write primitive
 * via a dynamically-built format string.
 *
 * Real, honest, fail-CLOSED stand-in: vm_region_64() always reports
 * KERN_FAILURE (never claims a region is read-only, since this target has
 * no real way to check). __printf_is_memory_read_only()'s own logic
 * («(kr == KERN_SUCCESS) && ...») then correctly falls through to "not
 * verified read-only", so every real %n use on this target hits
 * vfprintf.c's own os_crash() path and aborts -- i.e., %n is disabled
 * (safely, loudly, not silently) until real Mach IPC lands, rather than
 * this stub fabricating a "yes it's read-only" answer it can't actually
 * verify (which would be a real, silent security regression: it would
 * make the CVE-class %n-on-writable-format-string mitigation a no-op).
 * mach_task_self_ itself is never actually consulted given the above (kr
 * is always failure regardless of the target argument).
 *
 * mach_task_self_ RETIRED FROM THIS FILE 2026-08-14: build_libmalloc.sh
 * now links real third_party/xnu-7195/libsyscall/mach/mach_init.c
 * (unmodified), which defines the real mach_task_self_ populated via a
 * real task_self_trap() Mach trap - a strictly better real answer than
 * this file's old permanent MACH_PORT_NULL placeholder, and a duplicate-
 * symbol link error once both were linked together (real bug, found by
 * actually relinking this smoketest against libmalloc.a). vm_region_64()
 * below still never actually dereferences it as a real port (see this
 * comment's own reasoning above), so this is a pure improvement, not a
 * behavior change.
 */
