#!/bin/bash
# Builds the GNUstep tools that gnustep-make RUNS ON THE BUILD HOST while
# cross-building (DAR-390), into libc_build/gnustep/host-tools/, which
# gnustep_common.sh's gs_build_env puts first on PATH. Same idea as
# build_icu_host.sh: a cross build needs host-native copies of the
# generators it runs. The copies in root/System/Tools are arm64 iOS
# binaries, which macOS kills on exec.
#
#   plmerge -- bundle.make:306/316, application.make:293 and
#       framework.make merge a package's Info plist into the generated
#       Info-gnustep.plist with it.
#   pl2link -- application.make:296-298 writes each app's
#       Resources/<App>.desktop with it.
#
# Both are gnustep-base's own Tools/*.m, unmodified, compiled for the host
# against Apple's Foundation. They use only Foundation API plus two GNUstep
# names, GSPrintf (GNUstepBase/Additions.h) and RELEASE, which the prelude
# below defines; the GNUstep-only headers they import ("common.h",
# "GNUstepBase/Additions.h") are empty stand-ins, and their Foundation/*.h
# imports resolve to the host SDK's. pl2link also asks
# NSSearchPathForDirectoriesInDomains() where the app will be installed
# (pl2link.m:165). On the host Apple's answer would be /Applications, so
# for pl2link the prelude answers NSApplicationDirectory the way
# gnustep-base does on the target: from the GNUSTEP_<DOMAIN>_APPS lines of
# $GNUSTEP_CONFIG_FILE (the build copy of the target's GNUstep.conf,
# gnustep_common.sh), and its `which openapp` (pl2link.m:215) from the
# same file's GNUSTEP_SYSTEM_TOOLS. Apple's -[NSDictionary writeToFile:atomically:]
# writes XML plists, which gnustep-base reads (NSPropertyList, libxml2).
set -euo pipefail
cd "$(dirname "$0")"
OUT="$(cd libc_build && pwd -P)"
H="$OUT/gnustep/host-tools"
TOOLS="../../third_party/gnustep-base/Tools"
[ -f "$TOOLS/plmerge.m" ] || { echo "error: $TOOLS not found -- run setup_third_party.sh" >&2; exit 1; }
rm -rf "$H"; mkdir -p "$H/include/GNUstepBase"
: > "$H/include/common.h"
: > "$H/include/GNUstepBase/Additions.h"
cat > "$H/include/gs_host_prelude.h" <<'PRELUDE'
/* Generated by build_gnustep_host_tools.sh: the GNUstep names plmerge.m
 * and pl2link.m use beyond Apple's Foundation. */
#import <Foundation/Foundation.h>
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#define RELEASE(o) [(o) release]
static inline void GSPrintf(FILE *f, NSString *fmt, ...)
{
  va_list ap;
  va_start(ap, fmt);
  NSString *s = [[NSString alloc] initWithFormat: fmt arguments: ap];
  va_end(ap);
  fputs([s UTF8String], f);
  [s release];
}
#ifdef GS_HOST_APP_PATHS
/* NSApplicationDirectory from the target's GNUstep.conf (see the header
 * of build_gnustep_host_tools.sh). */
static NSArray *gs_host_search_paths(NSSearchPathDirectory d, NSSearchPathDomainMask m, BOOL e)
{
  const char *conf = getenv("GNUSTEP_CONFIG_FILE");
  NSString *text = conf ? [NSString stringWithContentsOfFile: [NSString stringWithUTF8String: conf]
                                                    encoding: NSUTF8StringEncoding error: NULL] : nil;
  NSMutableArray *out = [NSMutableArray array];
  static const NSSearchPathDomainMask masks[] = { NSUserDomainMask, NSLocalDomainMask,
                                                   NSNetworkDomainMask, NSSystemDomainMask };
  NSString *keys[] = { @"GNUSTEP_USER_APPS=", @"GNUSTEP_LOCAL_APPS=",
                       @"GNUSTEP_NETWORK_APPS=", @"GNUSTEP_SYSTEM_APPS=" };
  unsigned i;
  (void)e;
  if (d != NSApplicationDirectory || text == nil)
    return out;
  for (i = 0; i < 4; i++)
    if (m & masks[i])
      for (NSString *line in [text componentsSeparatedByString: @"\n"])
        if ([line hasPrefix: keys[i]])
          [out addObject: [line substringFromIndex: [keys[i] length]]];
  return out;
}
#define NSSearchPathForDirectoriesInDomains gs_host_search_paths
/* pl2link.m:215 runs `which openapp` for the .desktop Exec line; on the
 * host that finds root/'s copy under the host path. Answer it with the
 * target's GNUSTEP_SYSTEM_TOOLS/openapp from the same config file. */
static FILE *gs_host_popen(const char *cmd, const char *mode)
{
  if (strcmp(cmd, "which openapp") == 0)
    {
      const char *conf = getenv("GNUSTEP_CONFIG_FILE");
      NSString *text = conf ? [NSString stringWithContentsOfFile: [NSString stringWithUTF8String: conf]
                                                        encoding: NSUTF8StringEncoding error: NULL] : nil;
      for (NSString *line in [text componentsSeparatedByString: @"\n"])
        if ([line hasPrefix: @"GNUSTEP_SYSTEM_TOOLS="])
          {
            const char *p = [[NSString stringWithFormat: @"%@/openapp\n",
              [line substringFromIndex: 21]] UTF8String];
            return fmemopen(strdup(p), strlen(p), "r");
          }
    }
  return popen(cmd, mode);
}
#define popen gs_host_popen
#endif
PRELUDE
for t in plmerge pl2link; do
    extra=()
    [ "$t" = pl2link ] && extra=(-DGS_HOST_APP_PATHS)
    xcrun --sdk macosx clang -fno-objc-arc -O1 -Wno-deprecated-declarations ${extra[@]+"${extra[@]}"} \
        -I "$H/include" -include "$H/include/gs_host_prelude.h" -framework Foundation "$TOOLS/$t.m" -o "$H/$t"
done

# Check both on real inputs.
T="$H/test"; mkdir -p "$T"
echo '{ NSExecutable = "x"; }' > "$T/dest.plist"
echo '{ NSPrincipalClass = "Y"; }' > "$T/in.plist"
"$H/plmerge" "$T/dest.plist" "$T/in.plist"
plutil -p "$T/dest.plist" | grep -q '"NSPrincipalClass" => "Y"' && plutil -p "$T/dest.plist" | grep -q '"NSExecutable" => "x"' ||
    { echo "error: host plmerge did not merge the test plists" >&2; exit 1; }
printf 'GNUSTEP_SYSTEM_APPS=/usr/GNUstep/System/Applications\nGNUSTEP_SYSTEM_TOOLS=/usr/GNUstep/System/Tools\n' > "$T/GNUstep.conf"
echo '{ NSExecutable = "Ink"; ApplicationName = "Ink"; NSIcon = "Ink.tiff"; }' > "$T/Info-gnustep.plist"
GNUSTEP_CONFIG_FILE="$T/GNUstep.conf" GNUSTEP_INSTALLATION_DOMAIN=SYSTEM "$H/pl2link" "$T/Info-gnustep.plist" "$T/Ink.desktop"
grep -q '^Exec=/usr/GNUstep/System/Tools/openapp Ink$' "$T/Ink.desktop" &&
    grep -q '^Icon=/usr/GNUstep/System/Applications/Ink.app/Resources/Ink.tiff$' "$T/Ink.desktop" ||
    { cat "$T/Ink.desktop"; echo "error: host pl2link did not use the GNUstep.conf application path" >&2; exit 1; }
rm -rf "$T"
echo "wrote $H/plmerge and $H/pl2link (host)"
