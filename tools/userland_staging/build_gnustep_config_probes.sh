#!/bin/bash
# Builds gnustep-base's configure run-test probes for the target (DAR-388).
#
# gnustep-base's configure.ac decides ~20 settings with AC_RUN_IFELSE. A
# cross configure cannot run them, so it reads each answer from a
# --with-cross-compilation-info file as a cross_<var>=<value> line
# (configure.ac:175-190). This script compiles every one of those probe
# programs -- the real config/config.*.c|m files, plus the three inline
# sources configure.ac carries itself -- with the same target toolchain,
# runtime and dylibs gnustep-base will be built with, and writes a runner
# (run_probes.sh) that executes them on the target and prints the
# cross_<var>=<value> lines, using exactly the success/failure values each
# AC_RUN_IFELSE site assigns.
#
# A probe that does not compile or link for this target gets its failure
# value, which is what a native configure would conclude too (AC_RUN_IFELSE
# takes the failure branch on a compile/link error). The build error is kept
# in probes/<name>.err so the reason can be read rather than assumed.
#
#   build_gnustep_config_probes.sh            # build probes/ + run_probes.sh
#   build_gnustep_config_probes.sh --run IMG  # also install them into the
#       SD image IMG, boot it under QEMU (tools/boot_test.py) and write the
#       captured answers to x11_config/gnustep/cross-config-arm64-darwin
#
# The checked-in cross-config file is the output of --run; re-run it after
# changing libobjc, libsystem_c or libffi.
set -euo pipefail
cd "$(dirname "$0")"

XCODE12="/Applications/Xcode-12.app/Contents/Developer"
CLANG="$XCODE12/Toolchains/XcodeDefault.xctoolchain/usr/bin/clang"
SDK="$XCODE12/Platforms/iPhoneOS.platform/Developer/SDKs/iPhoneOS.sdk"
DAILY_XCODE="$(xcode-select -p 2>/dev/null)"
NEWLD_BINDIR="$DAILY_XCODE/Toolchains/XcodeDefault.xctoolchain/usr/bin"
SRC="../../third_party/gnustep-base"
CSU="../../third_party/Csu"
OUT="libc_build"
PUBHDRS="$OUT/objc4_public_headers"
P="$OUT/gnustep/probes"
DEST="/usr/local/libexec/gnustep-config-probes"
CROSS_OUT="x11_config/gnustep/cross-config-arm64-darwin"

[ -f "$SRC/configure.ac" ] || { echo "error: $SRC missing -- run setup_third_party.sh" >&2; exit 1; }
for f in libobjc.A.dylib objc4_public_headers/objc/runtime.h system/libffi.dylib system/libiconv.dylib \
         libffi_include/ffi.h system/libc++.dylib system/libunwind.dylib system/libsystem_blocks.dylib; do
    [ -e "$OUT/$f" ] || { echo "error: $OUT/$f not found -- run build_objc4.sh, build_libffi.sh, build_libiconv_dylib.sh, build_libcxx_dylib.sh, build_libunwind_dylib.sh and build_libsystem_blocks.sh first" >&2; exit 1; }
done

rm -rf "$P"; mkdir -p "$P"

SYS=("$OUT/system/libsystem_kernel.dylib" "$OUT/system/libsystem_platform.dylib"
     "$OUT/system/libsystem_blocks.dylib" "$OUT/system/libsystem_pthread.dylib"
     "$OUT/system/libsystem_malloc.dylib" "$OUT/system/libsystem_c.dylib"
     "$OUT/system/libsystem_m.dylib" "$OUT/system/libdyld.dylib" "$OUT/system/libSystem.B.dylib")
OBJC_LIBS=("$OUT/libobjc.A.dylib" "$OUT/system/libc++.dylib" "$OUT/system/libunwind.dylib")
# -D_FORTIFY_SOURCE=0: hosted probes (printf, sprintf), same as
# build_ffi_smoketest.sh. -DNeXT_RUNTIME -fnext-runtime: configure.ac:1254
# for the apple-gnu-gnu library combo.
CFLAGS=(-isysroot "$SDK" -target arm64-apple-ios14.4 -O0 -fno-stack-protector -D_FORTIFY_SOURCE=0
        -I "$SRC/config" -w)
OBJCFLAGS=(-x objective-c -fno-objc-arc -fobjc-exceptions -fblocks -DNeXT_RUNTIME -I "$PUBHDRS")

# Inline sources configure.ac carries itself.
cat > "$P/program_invocation_name.c" <<'EOF'
/* configure.ac:2828-2835 */
#include <string.h>
int
main (int argc, char *argv[])
{
  extern char *program_invocation_name;
  return (strcmp (program_invocation_name, argv[0]));
}
EOF
cat > "$P/iconv.c" <<'EOF'
/* configure.ac:3222-3224 (and 3261-3263 with -liconv) */
#include <iconv.h>
int main(int argc,char **argv)
{ return iconv_open("UTF-8//TRANSLIT","ASCII") == -1 ? 1 : 0; }
EOF

RUNNER="$P/run_probes.sh"
{
    echo '#!/bin/sh'
    echo "# Generated by build_gnustep_config_probes.sh. Prints gnustep-base cross_<var>=<value> lines."
    echo "cd $DEST || exit 1"
    echo 'echo GSPROBE_BEGIN'
} > "$RUNNER"

# probe <cross var> <pass value> <fail value> <source> <c|objc> [extra flags/libs...]
probe() {
    local var=$1 pass=$2 fail=$3 src=$4 lang=$5; shift 5
    local langflags=()
    [ "$lang" = objc ] && langflags=("${OBJCFLAGS[@]}")
    local libs=("${SYS[@]}")
    [ "$lang" = objc ] && libs=("${OBJC_LIBS[@]}" "${SYS[@]}")
    if "$CLANG" "${CFLAGS[@]}" ${langflags[@]+"${langflags[@]}"} "$@" -c "$src" -o "$P/$var.o" 2> "$P/$var.err" &&
       "$CLANG" -isysroot "$SDK" -target arm64-apple-ios14.4 -nostdlib -B"$NEWLD_BINDIR" -Wl,-fixup_chains \
           -o "$P/$var" "$CSU/start.s" "$CSU/crt.c" "$P/$var.o" "${EXTRA_LIBS[@]+"${EXTRA_LIBS[@]}"}" "${libs[@]}" \
           2>> "$P/$var.err" &&
       ./bind_target_audit.sh "$P/$var" >> "$P/$var.err" 2>&1; then
        echo "if ./$var >/dev/null 2>&1; then echo cross_$var=$pass; else echo cross_$var=$fail; fi" >> "$RUNNER"
        echo "built  $var"
    else
        rm -f "$P/$var"
        echo "echo 'cross_$var=$fail  # probe did not build for this target, see $P/$var.err'" >> "$RUNNER"
        echo "NOBUILD $var -> $fail ($(grep -m1 -E 'error|Undefined' "$P/$var.err" | cut -c1-110))"
    fi
}

C="$SRC/config"
EXTRA_LIBS=()
probe reuseaddr_ok 1 0 "$C/config.reuseaddr.c" c
probe gs_cv_objc_works yes no "$C/config.objc.m" objc
probe gs_cv_objc_compiler_supports_constant_string_class yes no "$C/config.constant-string-class.m" objc \
    -fconstant-string-class=FooConstantString
probe gs_cv_objc_load_method_worked yes no "$C/config.loadtest.m" objc
probe non_fragile yes no "$C/config.non-fragile-ivars.m" objc
probe have_unexpected yes no "$C/config.unexpected.m" objc
probe safe_initialize yes no "$C/config.initialize.m" objc
probe have_poll yes no "$C/config.poll-dev.c" c
probe VSPRINTF_RETURNS_LENGTH 1 0 "$C/config.vsprintf.c" c
probe VASPRINTF_RETURNS_LENGTH 1 0 "$C/config.vasprintf.c" c
probe NEED_WORD_ALIGNMENT 0 1 "$C/config.align.c" c
probe working_register_printf 1 0 "$C/config.printf.c" c
probe wide_register_printf 1 0 "$C/config.wprintf.c" c
probe gs_cv_program_invocation_name_worked yes no "$P/program_invocation_name.c" c
probe CMDLINE_TERMINATED 1 0 "$C/config.proccmd.c" c
probe have_kvm_env 1 0 "$C/config.kvmopen.c" c
EXTRA_LIBS=("$OUT/system/libffi.dylib")
probe ffi_ok yes no "$C/config.ffi.c" c -I "$OUT/libffi_include" \
    '-DSPI_AVAILABLE(...)=' '-DSPI_DEPRECATED(...)=' \
    '-D__API_AVAILABLE_PLATFORM_iosmac(x)=macCatalyst,introduced=x' \
    '-D__API_DEPRECATED_PLATFORM_iosmac(x,y)=macCatalyst,introduced=x,deprecated=y'
EXTRA_LIBS=()
probe found_iconv_libc yes no "$P/iconv.c" c
EXTRA_LIBS=("$OUT/system/libiconv.dylib")
probe found_iconv_liconv yes no "$P/iconv.c" c
EXTRA_LIBS=()
# There is no giconv on Darwin; configure.ac:3288 includes <giconv.h>.
echo "echo 'cross_found_iconv_lgiconv=no  # no <giconv.h> on Darwin'" >> "$RUNNER"
# Not a run test: configure.ac:2112 is AC_CHECK_FUNCS(objc_setProperty), a
# link check against the runtime. Answer it the same way, from libobjc's exports.
if nm -m "$OUT/libobjc.A.dylib" | grep -q "external _objc_setProperty$"; then o2=1; else o2=0; fi
echo "echo 'cross_objc2_runtime=$o2  # libobjc.A.dylib exports objc_setProperty: $o2'" >> "$RUNNER"
echo 'echo GSPROBE_END' >> "$RUNNER"
chmod 755 "$RUNNER"
echo "wrote $P (runner: $RUNNER)"

[ "${1:-}" = "--run" ] || exit 0
IMG="${2:?usage: $0 --run <sd image>}"
REPO="$(cd ../.. && pwd)"
case "$IMG" in /*) ;; *) IMG="$REPO/$IMG" ;; esac

DISK=$(hdiutil attach -nomount "$IMG" 2>/dev/null | awk 'NR==1{print $1}')
trap 'hdiutil detach "$DISK" >/dev/null 2>&1 || true' EXIT
SL="${DISK}s2"
diskutil mount "$SL" >/dev/null
MNT=$(diskutil info "$SL" | awk -F': +' '/Mount Point/{print $2}')
# Everything the probes load that the image might carry an older copy of.
install -d "$MNT$DEST"
for f in "$P"/*; do case "$f" in *.o|*.err|*.c) ;; *) install -m 755 "$f" "$MNT$DEST/" ;; esac; done
install -m 755 "$OUT/libobjc.A.dylib" "$OUT/libobjc-trampolines.dylib" \
    "$OUT/system/libffi.dylib" "$OUT/system/libffi-trampolines.dylib" "$MNT/usr/lib/"
diskutil unmount "$SL" >/dev/null
hdiutil detach "$DISK" >/dev/null; trap - EXIT

LOG="$(mktemp -t gsprobe)"
(cd "$REPO" && SD_IMAGE="$IMG" tools/boot_test.py --login --timeout 900 --log "$LOG" \
    --cmd "$DEST/run_probes.sh" --expect '\nGSPROBE_END' < /dev/null | tail -1)
mkdir -p "$(dirname "$CROSS_OUT")"
{
    echo "# gnustep-base cross-compilation answers for arm64 Darwin 20 on this port (objc4 runtime)."
    echo "# Generated by tools/userland_staging/build_gnustep_config_probes.sh --run: each value is"
    echo "# the real exit status of that configure probe, run on the target under QEMU."
    tr -d '\r' < "$LOG" | sed -n '/^GSPROBE_BEGIN/,/^GSPROBE_END/p' | grep '^cross_'
} > "$CROSS_OUT"
n=$(grep -c '^cross_' "$CROSS_OUT")
[ "$n" -eq 21 ] || { echo "error: captured $n answers, expected 21 -- see $LOG" >&2; exit 1; }
echo "wrote $CROSS_OUT ($n answers; log $LOG)"
