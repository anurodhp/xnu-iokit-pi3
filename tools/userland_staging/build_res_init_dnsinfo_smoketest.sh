#!/bin/bash
# Builds libc_build/res_init_dnsinfo_smoketest.macho -- DAR-285's real
# end-to-end verification client. See res_init_dnsinfo_smoketest.c's own
# header for exactly what it proves and why nothing already on the image
# could prove it.
#
# Same real dynamic-link recipe as build_notifyd_smoketest.sh
# (generic_main_wrapper.c + Csu start.s/crt.c + the NEWLD_BINDIR override
# for Xcode 12's ld64-609 -fixup_chains crash, docs/backlog.md item d9) --
# not repeated here.
#
# Links libresolv.dylib EXPLICITLY, and that is the whole point: this
# binary must reach dns_configuration_copy() through the stock, shipped
# libresolv, exactly as any future getaddrinfo/ping consumer would. It
# deliberately does NOT compile configd/dnsinfo/dnsinfo_copy.c into
# itself the way build_scutil.sh used to -- a local copy would make the
# test pass while proving nothing about libresolv, which is precisely the
# gap DAR-285 exists to close. The gate at the end of this script asserts
# that direction.
#
# libresolv.dylib is listed BEFORE libSystem.B.dylib on the link line on
# purpose: libSystem.B.dylib LC_REEXPORT_DYLIBs libresolv, so ld64 would
# happily resolve _dns_configuration_copy through it and record the bind
# against libSystem instead -- which still works at runtime (a reexport
# closure IS searched, unlike the plain-link case in CLAUDE.md's DAR-217
# writeup) but makes this test's own nm-based gate unable to tell the
# real owner from the umbrella.
set -euo pipefail
cd "$(dirname "$0")"
OUT="libc_build"
CSU="../../third_party/Csu"
LIBRESOLV="../../third_party/libresolv"

XCODE12="/Applications/Xcode-12.app/Contents/Developer"
CLANG="$XCODE12/Toolchains/XcodeDefault.xctoolchain/usr/bin/clang"
SDK="$XCODE12/Platforms/iPhoneOS.platform/Developer/SDKs/iPhoneOS.sdk"
if [ ! -x "$CLANG" ] || [ ! -d "$SDK" ]; then
    echo "error: Xcode-12.app not found at $XCODE12" >&2
    exit 1
fi
if [ ! -d "$CSU" ]; then
    echo "error: $CSU not found -- run ./setup_third_party.sh first" >&2
    exit 1
fi
if [ ! -f "$LIBRESOLV/resolv.h" ]; then
    echo "error: $LIBRESOLV/resolv.h not found -- run ./setup_third_party.sh first" >&2
    exit 1
fi

DAILY_XCODE="$(xcode-select -p 2>/dev/null)"
NEWLD_BINDIR="$DAILY_XCODE/Toolchains/XcodeDefault.xctoolchain/usr/bin"
if [ ! -x "$NEWLD_BINDIR/ld" ]; then
    echo "error: no usable 'ld' found under the daily-driver Xcode ($DAILY_XCODE)" >&2
    exit 1
fi

for f in system/libsystem_c.dylib system/libsystem_pthread.dylib \
         system/libsystem_malloc.dylib system/libsystem_kernel.dylib \
         system/libsystem_platform.dylib system/libsystem_blocks.dylib \
         system/libdispatch.dylib system/libxpc.dylib \
         system/libsystem_notify.dylib \
         system/libdyld.dylib system/libSystem.B.dylib system/libresolv.dylib; do
    if [ ! -f "$OUT/$f" ]; then
        echo "error: $OUT/$f not found -- run the libSystem tier build scripts first" >&2
        exit 1
    fi
done
# Named explicitly, on its own, so tools/userland_staging/gen_build_order.py
# really orders this script after it (that tool only reads the literal
# "run build_X.sh first" idiom -- the generic loop message above is
# invisible to it, and this test is meaningless against a libresolv.dylib
# built before DAR-285 put the real dnsinfo client in it).
if [ ! -f "$OUT/system/libresolv.dylib" ]; then
    echo "error: $OUT/system/libresolv.dylib not found -- run build_libresolv_dylib.sh first" >&2
    exit 1
fi
# Real, vendored dnsinfo.h (dns_config_t/dns_resolver_t), generated by
# build_libresolv.sh from the pinned configd tag -- byte-identical to
# configd/dnsinfo/dnsinfo.h, verified by diff.
if [ ! -f "$OUT/compat_include/dnsinfo.h" ]; then
    echo "error: $OUT/compat_include/dnsinfo.h not found -- run build_libresolv.sh first" >&2
    exit 1
fi

# Real staleness gate (staleness_check.sh, DAR-271). This test's whole
# value is that it exercises the CURRENT libresolv.dylib -- silently
# testing one built before the dnsinfo client landed would report a
# meaningless result. Checked against the real source libresolv's dnsinfo
# half is built from, not against this file.
./staleness_check.sh "$OUT/system/libresolv.dylib" RES_INIT_SMOKETEST_ALLOW_STALE_LIBRESOLV \
    ../../third_party/configd/dnsinfo -name '*.c' -o -name '*.h'
./staleness_check.sh "$OUT/system/libresolv.dylib" RES_INIT_SMOKETEST_ALLOW_STALE_LIBRESOLV \
    ../../third_party/configd/libSystemConfiguration -name '*.c' -o -name '*.h'

# -DUSE__RES_9 matches how build_libresolv.sh really compiles libresolv,
# and is what makes <resolv.h>'s `res_init` macro-expand to the real
# exported `res_9_init` symbol. Getting this wrong produces a clean
# compile and an undefined `_res_init` at link time.
CFLAGS="-isysroot $SDK -target arm64-apple-ios14.4 -c -ffreestanding -fno-builtin -fno-stack-protector -O0 -Wall \
    -DUSE__RES_9 -DPRIVATE -Wno-nullability-completeness \
    -I $LIBRESOLV -I $OUT/compat_include"

"$CLANG" $CFLAGS -Dmain=res_init_dnsinfo_real_main res_init_dnsinfo_smoketest.c \
    -o "$OUT/res_init_dnsinfo_smoketest.o"
"$CLANG" -isysroot "$SDK" -target arm64-apple-ios14.4 -c -ffreestanding -fno-builtin \
    -fno-stack-protector -O0 -Wall \
    -DREAL_MAIN=res_init_dnsinfo_real_main -DCMD_NAME='"res_init_dnsinfo_smoketest"' \
    generic_main_wrapper.c -o "$OUT/res_init_dnsinfo_smoketest_wrapper.o"

rm -f "$OUT/res_init_dnsinfo_smoketest.macho"
"$CLANG" -isysroot "$SDK" -target arm64-apple-ios14.4 -nostdlib -DCRT_DYNAMIC_LINKING \
    -B"$NEWLD_BINDIR" \
    -Wl,-fixup_chains \
    -o "$OUT/res_init_dnsinfo_smoketest.macho" \
    "$CSU/start.s" "$CSU/crt.c" \
    "$OUT/res_init_dnsinfo_smoketest_wrapper.o" "$OUT/res_init_dnsinfo_smoketest.o" \
    "$OUT/system/libresolv.dylib" \
    "$OUT/system/libsystem_c.dylib" "$OUT/system/libsystem_pthread.dylib" \
    "$OUT/system/libsystem_malloc.dylib" "$OUT/system/libsystem_kernel.dylib" \
    "$OUT/system/libsystem_platform.dylib" "$OUT/system/libsystem_blocks.dylib" \
    "$OUT/system/libdispatch.dylib" "$OUT/system/libxpc.dylib" \
    "$OUT/system/libsystem_notify.dylib" \
    "$OUT/system/libdyld.dylib" "$OUT/system/libSystem.B.dylib"

M="$OUT/res_init_dnsinfo_smoketest.macho"
otool -l "$M" | grep -A2 "cmd LC_LOAD_DYLINKER" | grep -q "/usr/lib/dyld" || {
    echo "error: no LC_LOAD_DYLINKER /usr/lib/dyld -- not a real dynamic executable" >&2
    exit 1
}
otool -l "$M" | grep -q "cmd LC_MAIN" || {
    echo "error: no LC_MAIN -- see build_simple_cmds.sh's LINK_DYLIBS comment" >&2
    exit 1
}

# THE gate: this test is worthless unless both entry points really come
# from libresolv.dylib rather than a local copy or the libSystem umbrella.
for s in _dns_configuration_copy _res_9_init; do
    line=$(nm -m "$M" 2>/dev/null | grep -E "external $s( |\$)" || true)
    case "$line" in
        *"(undefined)"*"(from libresolv)"*) ;;
        "") echo "error: $M has no reference to $s at all" >&2; exit 1 ;;
        *) echo "error: $M does not bind $s to libresolv -- got: $line" >&2; exit 1 ;;
    esac
done
echo "wrote $M ($(wc -c < "$M") bytes, real dynamic executable)"
echo "  _dns_configuration_copy + _res_9_init both bind the real libresolv.dylib"

./bind_target_audit.sh "$M" || {
    echo "error: $M has an unresolvable two-level bind -- it would abort at dyld load" >&2
    exit 1
}
echo "  install: tools/init_binary/inject_into_sd_image.sh puts it at /usr/local/bin/"
