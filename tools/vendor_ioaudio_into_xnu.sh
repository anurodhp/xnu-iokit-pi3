#!/bin/bash
#
# Vendors real Apple IOAudioFamily (third_party/IOAudioFamily, IOAudioFamily-300.6.1,
# macos-112 manifest pin; our fork anurodhp/IOAudioFamily branch iokit-port) into
# the kernel source tree so it is COMPILED INTO the kernel, same shape and
# reasons as tools/vendor_iographics_into_xnu.sh (read its header: the
# copy-not-include-path rationale and the divergence guard are identical):
#
#   third_party/xnu-7195/iokit/Audio/IOAudioFamily/  <- the 13 .cpp
#   third_party/xnu-7195/iokit/IOKit/audio/          <- the headers; the sources
#       reach them both as <IOKit/audio/X.h> and as "X.h" (per-object -I)
#   + one line per source in iokit/conf/files
#
# PCMBlitterLib is not vendored: nothing in the family's sources includes it
# (it is for userland/HAL-side format conversion in Apple's kext build).
# Source fixes live on the fork, never here. The copies are GENERATED.
# tools/ioaudio_gap_audit.sh is the fast pre-check. Idempotent.
set -e

REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$REPO_ROOT"

XNU="third_party/xnu-7195"
IOA="third_party/IOAudioFamily"
CONF="$XNU/iokit/conf/files"
MKT="$XNU/iokit/conf/Makefile.template"

if [ ! -d "$XNU/iokit/conf" ]; then
	echo "error: $XNU not found - run ./setup_third_party.sh" >&2
	exit 1
fi
if [ ! -f "$IOA/IOAudioEngine.cpp" ]; then
	echo "error: $IOA not found - run ./setup_third_party.sh" >&2
	exit 1
fi
# Must be the fork (DARW-310): upstream still has vecLib and a NULL-to-uint32_t.
if grep -q "vecLib/vecLib.h" "$IOA/IOAudioEngineMixer.cpp"; then
	echo "error: $IOA lacks this project's fixes -- not the anurodhp/IOAudioFamily" >&2
	echo "       iokit-port fork. Re-clone it: rm -rf $IOA && ./setup_third_party.sh" >&2
	exit 1
fi

A_SRC="$XNU/iokit/Audio/IOAudioFamily"
A_HDR="$XNU/iokit/IOKit/audio"
mkdir -p "$A_SRC" "$A_HDR"

diverged=()
copy_into() {
	local dst="$1"; shift
	local f d
	for f in "$@"; do
		d="$dst/$(basename "$f")"
		if [ -e "$d" ] && ! cmp -s "$f" "$d"; then
			if [ -n "$(git -C "$XNU" status --porcelain -- "${d#$XNU/}" 2>/dev/null)" ]; then
				diverged+=("${d#$XNU/}")
				continue
			fi
		fi
		cp "$f" "$d"
	done
}
copy_into "$A_SRC" "$IOA"/*.cpp
copy_into "$A_HDR" "$IOA"/*.h
if [ ${#diverged[@]} -ne 0 ]; then
	echo "error: vendored files differ from source AND have uncommitted edits in the" >&2
	echo "       XNU tree; refusing to overwrite:" >&2
	printf '         git -C %s diff -- %s\n' "$XNU" "${diverged[@]}" >&2
	echo "       Move the fix into anurodhp/IOAudioFamily (iokit-port), then re-run." >&2
	exit 1
fi

MARKER="# --- Audio (IOAudioFamily-300.6.1), vendored by tools/vendor_ioaudio_into_xnu.sh ---"
CONFBLOCK="$(mktemp)"
OBJS=""
{
	echo "$MARKER"
	for f in "$A_SRC"/*.cpp; do
		printf 'iokit/Audio/IOAudioFamily/%s\t\toptional iokitcpp\n' "$(basename "$f")"
		OBJS="$OBJS $(basename "${f%.cpp}").cpo"
	done
} > "$CONFBLOCK"
python3 - "$CONF" "$CONFBLOCK" "$MARKER" <<'PYEOF'
import sys
conf, blockf, marker = sys.argv[1:4]
lines = open(conf).read().split("\n")
block = open(blockf).read().rstrip("\n").split("\n")
if marker in lines:
    a = lines.index(marker)
    b = a
    while b < len(lines) and lines[b].strip() != "":
        b += 1
    lines = lines[:a] + block + lines[b:]
else:
    while lines and lines[-1] == "":
        lines.pop()
    lines += [""] + block + [""]
open(conf, "w").write("\n".join(lines))
PYEOF
rm -f "$CONFBLOCK"

# Object names must be unique across every conf/files.
for o in $OBJS; do
	src="${o%.cpo}"
	n=$(LC_ALL=C grep -cE "/$src\.(c|cpp|s)[[:space:]]" "$XNU"/*/conf/files | awk -F: '{s+=$NF} END {print s+0}')
	if [ "$n" != 1 ]; then
		echo "error: object name $o is listed $n times across */conf/files" >&2
		exit 1
	fi
done

BEGIN="# BEGIN IOAudioFamily per-object flags -- generated by tools/vendor_ioaudio_into_xnu.sh, do not edit"
END="# END IOAudioFamily per-object flags"
BLOCK="$(mktemp)"
trap 'rm -f "$BLOCK"' EXIT
{
	echo "$BEGIN"
	echo "# The sources include their headers both as <IOKit/audio/X.h> and \"X.h\"."
	echo "IOAUDIO_OBJS =$OBJS"
	echo "\$(foreach o,\$(IOAUDIO_OBJS),\$(eval \$(o)_CFLAGS_ADD += -I\$(SRCROOT)/iokit/IOKit/audio))"
	echo "$END"
} > "$BLOCK"
python3 - "$MKT" "$BLOCK" "$BEGIN" "$END" <<'PYEOF'
import sys
mkt, blockf, begin, end = sys.argv[1:5]
text = open(mkt).read()
block = open(blockf).read().rstrip("\n")
if begin in text:
    a = text.index(begin)
    b = text.index(end, a) + len(end)
    text = text[:a] + block + text[b:]
else:
    text = text.rstrip("\n") + "\n\n" + block + "\n"
open(mkt, "w").write(text)
PYEOF
echo "IOAudioFamily vendored: $(ls "$A_SRC"/*.cpp | wc -l) sources"
echo "  objects:$OBJS"
